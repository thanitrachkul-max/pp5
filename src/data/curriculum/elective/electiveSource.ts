function secondaryOutcomes(counts: readonly number[]): BotanicalOutcomeDef[] {
  return counts.flatMap((count, index) => {
    const strandNo = index + 1;
    return SECONDARY_OUTCOMES_BY_STRAND[strandNo]
      .slice(0, count)
      .map((text) => ({ strandNo, text }));
  });
}

